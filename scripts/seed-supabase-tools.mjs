#!/usr/bin/env node
// Upserts the `tools` reference table in Supabase from every
// data/catalog/*/tools.json. Idempotent on slug. Run after the migration and
// whenever the catalog changes (the setup workflow does both).
//
//   SUPABASE_URL=https://<ref>.supabase.co SUPABASE_SERVICE_ROLE_KEY=... node scripts/seed-supabase-tools.mjs
//   SUPABASE_ACCESS_TOKEN=sbp_... SUPABASE_PROJECT_REF=<ref> node scripts/seed-supabase-tools.mjs   # resolves the key itself
//   node scripts/seed-supabase-tools.mjs --dry-run                                                   # print rows, no network
//   node scripts/seed-supabase-tools.mjs --sql > tools.sql                                            # upsert statements for the SQL editor
//
// Domain rule (mirrors public.domain_matches in the migration): a claimant
// auto-verifies when their email domain equals the tool domain, is a parent of
// it (google.com ~ cloud.google.com) or a subdomain of it. Tools hosted on a
// shared domain get domain = null: nobody auto-verifies those.

import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dryRun = process.argv.includes('--dry-run');
const asSql = process.argv.includes('--sql');

// Env var per catalog adapter, as scripts/run-voice.mjs reads them. Adapters
// not listed here (http_json, aws_polly, open:*) cannot take a vendor key yet.
const KEY_ADAPTERS = new Set(['inworld', 'openai', 'elevenlabs', 'cartesia', 'openai_chat', 'anthropic', 'gemini']);
// Hosts many unrelated projects live on. A github.com mailbox proves nothing about Piper.
const SHARED_HOSTS = new Set(['github.com', 'gitlab.com', 'huggingface.co', 'sourceforge.net', 'bitbucket.org', 'npmjs.com', 'pypi.org']);

export function domainOf(website) {
  let host;
  try { host = new URL(website).hostname.toLowerCase(); } catch { return null; }
  host = host.replace(/^www\./, '');
  if (SHARED_HOSTS.has(host) || !/^[a-z0-9.-]+\.[a-z]{2,}$/.test(host)) return null;
  return host;
}

// Catalog spellings that differ from the adapters table.
const ADAPTER_ALIASES = { 'openai-chat': 'openai_chat', 'anthropic-messages': 'anthropic' };

/** Open weights: flagged in the catalog, or an open:* / open-llm:* adapter. Nothing to claim. */
export function isOpenWeights(t) {
  return t.open_weights === true || /^open([-:]|$)/.test(String(t.adapter ?? ''));
}

export function toolRow(category, t) {
  const adapter = String(t.adapter ?? 'none');
  const keyAdapter = ADAPTER_ALIASES[adapter] ?? adapter;
  return {
    slug: t.slug,
    category_slug: category,
    name: t.name,
    vendor: t.vendor,
    website: t.website,
    domain: domainOf(t.website),
    adapter,
    claimable: !isOpenWeights(t),
    key_adapter: KEY_ADAPTERS.has(keyAdapter) ? keyAdapter : null,
  };
}

function loadCatalog() {
  const dir = join(root, 'data/catalog');
  const rows = [];
  for (const category of readdirSync(dir)) {
    const file = join(dir, category, 'tools.json');
    if (!existsSync(file)) continue;
    for (const t of JSON.parse(readFileSync(file, 'utf8'))) rows.push(toolRow(category, t));
  }
  return rows;
}

/** SUPABASE_URL + service-role key, from the env or via the Management API. */
async function resolveAdmin() {
  let url = process.env.SUPABASE_URL;
  let key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const ref = process.env.SUPABASE_PROJECT_REF;
  const token = process.env.SUPABASE_ACCESS_TOKEN;
  if (!url && ref) url = `https://${ref}.supabase.co`;
  if (!key && token && ref) {
    const res = await fetch(`https://api.supabase.com/v1/projects/${ref}/api-keys?reveal=true`, { headers: { Authorization: `Bearer ${token}` } });
    if (!res.ok) throw new Error(`Management API ${res.status} while resolving the service-role key`);
    const keys = await res.json();
    key = keys.find((k) => k.name === 'service_role')?.api_key;
    if (!key) throw new Error('Management API returned no service_role key');
  }
  if (!url || !key) throw new Error('set SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY, or SUPABASE_ACCESS_TOKEN + SUPABASE_PROJECT_REF');
  return { url: url.replace(/\/+$/, ''), key };
}

const rows = loadCatalog();
if (asSql) {
  const q = (v) => (v === null ? 'NULL' : typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
  const cols = ['slug', 'category_slug', 'name', 'vendor', 'website', 'domain', 'adapter', 'claimable', 'key_adapter'];
  console.log(`-- generated by scripts/seed-supabase-tools.mjs --sql; ${rows.length} tools`);
  for (const r of rows) {
    console.log(`INSERT INTO public.tools (${cols.join(', ')}) VALUES (${cols.map((c) => q(r[c])).join(', ')})\n  ON CONFLICT (slug) DO UPDATE SET ${cols.slice(1).map((c) => `${c} = EXCLUDED.${c}`).join(', ')};`);
  }
  process.exit(0);
}
if (dryRun) {
  for (const r of rows) console.log(`${r.category_slug}/${r.slug}\tdomain=${r.domain ?? '-'}\tclaimable=${r.claimable}\tkey_adapter=${r.key_adapter ?? '-'}`);
  console.log(`${rows.length} tools (dry run, nothing sent)`);
  process.exit(0);
}

const { url, key } = await resolveAdmin();
const res = await fetch(`${url}/rest/v1/tools?on_conflict=slug`, {
  method: 'POST',
  headers: {
    apikey: key,
    Authorization: `Bearer ${key}`,
    'Content-Type': 'application/json',
    Prefer: 'resolution=merge-duplicates,return=minimal',
  },
  body: JSON.stringify(rows),
});
if (!res.ok) {
  console.error(`upsert failed: HTTP ${res.status} ${(await res.text()).slice(0, 400)}`);
  process.exit(1);
}
console.log(`upserted ${rows.length} tools into ${url.replace(/^https?:\/\//, '')} (${rows.filter((r) => r.key_adapter).length} accept keys, ${rows.filter((r) => r.claimable).length} claimable)`);
