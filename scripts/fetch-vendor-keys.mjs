#!/usr/bin/env node
// For CI: pulls the active vendor keys out of Supabase (view
// active_keys_for_runner, service role only) and writes shell `export` lines
// the benchmark workflow sources before running the adapters.
//
//   node scripts/fetch-vendor-keys.mjs --out .vendor-keys.env
//   source .vendor-keys.env && node scripts/run-voice.mjs --tool elevenlabs
//
// Auth, either:
//   SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY, or
//   SUPABASE_ACCESS_TOKEN + SUPABASE_PROJECT_REF (resolves the service-role key
//   from the Management API at run time, so no long-lived key sits in CI).
//
// Per key it writes both the adapter env var the runner reads today
// (e.g. INWORLD_API_KEY) and a per-tool var TOOLWARS_KEY_<SLUG> for when two
// tools share an adapter. Nothing secret is ever printed to stdout/stderr; on
// GitHub Actions each value is registered with ::add-mask:: first.
//
// Exit codes: 0 keys written (possibly zero), 2 config missing, 1 request failed.
// A missing config exits 2 so the workflow can treat "claims not set up yet"
// as "no vendor keys", not as a failure.

import { writeFileSync, chmodSync } from 'node:fs';

const args = Object.fromEntries(
  process.argv.slice(2).reduce((acc, a, i, arr) => {
    if (a.startsWith('--')) acc.push([a.slice(2), arr[i + 1] && !arr[i + 1].startsWith('--') ? arr[i + 1] : 'true']);
    return acc;
  }, [])
);
const outPath = args.out ?? '.vendor-keys.env';

function mask(value) {
  return value.length > 4 ? `${'*'.repeat(Math.min(8, value.length - 4))}${value.slice(-4)}` : '****';
}

function shellQuote(s) {
  return `'${String(s).replace(/'/g, `'\\''`)}'`;
}

async function resolveAdmin() {
  let url = process.env.SUPABASE_URL;
  let key = process.env.SUPABASE_SERVICE_ROLE_KEY;
  const ref = process.env.SUPABASE_PROJECT_REF;
  const token = process.env.SUPABASE_ACCESS_TOKEN;
  if (!url && ref) url = `https://${ref}.supabase.co`;
  if (!key && token && ref) {
    const res = await fetch(`https://api.supabase.com/v1/projects/${ref}/api-keys?reveal=true`, { headers: { Authorization: `Bearer ${token}` } });
    if (!res.ok) throw new Error(`Management API ${res.status} while resolving the service-role key`);
    key = (await res.json()).find((k) => k.name === 'service_role')?.api_key;
    if (!key) throw new Error('Management API returned no service_role key');
    if (process.env.GITHUB_ACTIONS) console.log(`::add-mask::${key}`);
  }
  if (!url || !key) return null;
  return { url: url.replace(/\/+$/, ''), key };
}

const admin = await resolveAdmin();
if (!admin) {
  console.error('fetch-vendor-keys: no Supabase config (SUPABASE_URL + SUPABASE_SERVICE_ROLE_KEY, or SUPABASE_ACCESS_TOKEN + SUPABASE_PROJECT_REF); writing an empty file');
  writeFileSync(outPath, '# no vendor keys: claims backend not configured\n', { mode: 0o600 });
  process.exit(2);
}

const res = await fetch(`${admin.url}/rest/v1/active_keys_for_runner?select=key_id,tool_slug,category_slug,adapter,key_env,key_last4,validated_at,secret&order=validated_at.asc`, {
  headers: { apikey: admin.key, Authorization: `Bearer ${admin.key}`, Accept: 'application/json' },
});
if (!res.ok) {
  console.error(`fetch-vendor-keys: HTTP ${res.status} ${(await res.text()).slice(0, 300)}`);
  process.exit(1);
}
const rows = await res.json();

const lines = ['# generated by scripts/fetch-vendor-keys.mjs; do not commit', 'set +x'];
const byEnv = new Map();
for (const r of rows) {
  if (!r.secret) continue;
  if (process.env.GITHUB_ACTIONS) console.log(`::add-mask::${r.secret}`);
  const perTool = `TOOLWARS_KEY_${r.tool_slug.toUpperCase().replace(/[^A-Z0-9]/g, '_')}`;
  lines.push(`export ${perTool}=${shellQuote(r.secret)}`);
  if (r.key_env) {
    if (byEnv.has(r.key_env)) console.error(`fetch-vendor-keys: ${r.key_env} set by both ${byEnv.get(r.key_env)} and ${r.tool_slug}; the later one wins, use ${perTool} to disambiguate`);
    byEnv.set(r.key_env, r.tool_slug);
    lines.push(`export ${r.key_env}=${shellQuote(r.secret)}`);
  }
  console.error(`${r.category_slug}/${r.tool_slug}: ${r.key_env ?? perTool} ${mask(r.secret)} (last4 ${r.key_last4}, validated ${r.validated_at ?? 'n/a'})`);
}
lines.push(`export TOOLWARS_VENDOR_TOOLS=${shellQuote(rows.map((r) => r.tool_slug).join(','))}`);

writeFileSync(outPath, lines.join('\n') + '\n', { mode: 0o600 });
chmodSync(outPath, 0o600);
console.error(`fetch-vendor-keys: ${rows.length} active key(s) written to ${outPath}`);
if (process.env.GITHUB_OUTPUT) writeFileSync(process.env.GITHUB_OUTPUT, `vendor_tools=${rows.map((r) => r.tool_slug).join(',')}\ncount=${rows.length}\n`, { flag: 'a' });
